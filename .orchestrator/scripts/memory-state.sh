#!/usr/bin/env bash
# /sync-memory step 1: write the git-derived part of memory/PROJECT_STATE.md.
# Replaces everything between the state markers with each repo's base-branch commit, its open PRs
# and what is left to clean up (worktrees and branches whose PR is merged or closed), straight from
# git and gh, and stamps the sync date. Nothing here is written by a model.
# Repos come from .orchestrator/orchestrator.conf. Without a remote or gh, that part is skipped with a warning.
set -euo pipefail
set -f # repo names are split on spaces, never globbed
root="$(cd "$(dirname "$0")/../.." && pwd)"  # the workspace root, whichever tool runs this
# shellcheck disable=SC1091
. "$root/.orchestrator/orchestrator.conf"
file="$root/memory/PROJECT_STATE.md"
begin='<!-- state:begin (generated by .orchestrator/scripts/memory-state.sh, do not edit) -->'
end='<!-- state:end -->'

grep -qF "$begin" "$file" && grep -qF "$end" "$file" || { echo "memory-state: markers missing in $file" >&2; exit 1; }

rgit() { local r=$1; shift; if [ -n "${GIT_WRAPPER:-}" ]; then bash "$root/$GIT_WRAPPER" "$r" "$@"; else git -C "$root/$r" "$@"; fi; }
label() { [ "$1" = "." ] && basename "$root" || echo "$1"; }
base() { # BASE_BRANCHES entry, else origin/HEAD, else main, else master
  local kv b
  for kv in ${BASE_BRANCHES:-}; do [ "${kv%%=*}" = "$1" ] && { echo "${kv#*=}"; return; }; done
  b=$(git -C "$root/$1" symbolic-ref -q --short refs/remotes/origin/HEAD 2>/dev/null) && { echo "${b#origin/}"; return; }
  for b in main master; do git -C "$root/$1" rev-parse -q --verify "refs/heads/$b" >/dev/null 2>&1 && { echo "$b"; return; }; done
  echo main
}

block=$(mktemp)
{
  echo "$begin"
  echo "## Base branches"
  echo "| Repo | Branch | Commit | Date |"
  echo "|---|---|---|---|"
  for r in $REPOS; do
    b=$(base "$r"); ref=$b
    if git -C "$root/$r" remote get-url origin >/dev/null 2>&1; then
      rgit "$r" fetch -q origin "$b" 2>/dev/null && ref="origin/$b" || echo "memory-state: fetch of $b failed in $r, using local $b" >&2
    fi
    if git -C "$root/$r" rev-parse -q --verify "$ref^{commit}" >/dev/null 2>&1; then
      git -C "$root/$r" log -1 --format="| $(label "$r") | \`$b\` | \`%h\` | %cs |" "$ref"
    else
      echo "memory-state: base branch '$b' not found in $r; set it in BASE_BRANCHES" >&2
      echo "| $(label "$r") | \`$b\` | missing | |"
    fi
  done
  echo
  echo "## Open PRs"
  echo "| Repo | PR | Branch | Draft | Review | Mergeable | Checks |"
  echo "|---|---|---|---|---|---|---|"
  for r in $REPOS; do
    command -v gh >/dev/null && git -C "$root/$r" remote get-url origin >/dev/null 2>&1 || { echo "memory-state: no gh or remote for $r, PRs skipped" >&2; continue; }
    l=$(label "$r")
    (cd "$root/$r" && gh pr list --state open --limit 50 \
      --json number,headRefName,isDraft,reviewDecision,reviewRequests,mergeable,statusCheckRollup \
      --jq ".[] | \"| $l | #\(.number) | \`\(.headRefName)\` | \(if .isDraft then \"yes\" else \"no\" end) | \(
          if .reviewDecision == \"\" or .reviewDecision == null then
            (if (.reviewRequests | length) > 0 then \"requested\" else \"none\" end)
          else (.reviewDecision | ascii_downcase) end) | \(.mergeable | ascii_downcase) | \(
          [.statusCheckRollup[]? | if (.conclusion // \"\") != \"\" then .conclusion elif (.state // \"\") != \"\" and .state != \"PENDING\" then .state else \"pending\" end | ascii_downcase] | unique | if length == 0 then \"none\" else join(\",\") end) |\"") \
      || echo "memory-state: gh pr list failed in $r" >&2
  done
  echo
  echo "## Cleanup"
  echo "Worktrees and local branches whose latest PR is merged or closed. Check uncommitted files before removing."
  found=0; unchecked=""
  for r in $REPOS; do
    command -v gh >/dev/null && git -C "$root/$r" remote get-url origin >/dev/null 2>&1 || { unchecked+=" $(label "$r")"; continue; }
    l=$(label "$r")
    # head branch <TAB> number <TAB> state, newest PR first
    prs=$(cd "$root/$r" && gh pr list --state all --limit 200 --json number,state,headRefName \
      --jq '.[] | "\(.headRefName)\t\(.number)\t\(.state | ascii_downcase)"' 2>/dev/null) \
      || { echo "memory-state: gh pr list failed in $r, cleanup skipped" >&2; unchecked+=" $l"; continue; }
    pr_of() { printf '%s\n' "$prs" | awk -F'\t' -v b="$1" '$1 == b { print "#" $2 " " $3; exit }'; }
    in_wt=" "
    while IFS=$'\t' read -r path branch; do
      [ -n "$branch" ] || continue
      in_wt+="$branch "
      [ "$path" = "$(cd "$root/$r" && pwd -P)" ] && continue # the repo's own checkout
      pr=$(pr_of "$branch"); case "$pr" in *" merged"|*" closed") ;; *) continue ;; esac
      dirty=$(git -C "$path" status --porcelain 2>/dev/null | wc -l | tr -d ' ')
      echo "- \`$l\` worktree \`${path#$root/}\` (\`$branch\`, $dirty uncommitted): $pr"; found=1
    done < <(git -C "$root/$r" worktree list --porcelain | awk '
      /^worktree / { p = substr($0, 10) } /^branch / { sub("refs/heads/", "", $2); print p "\t" $2 }')
    for branch in $(git -C "$root/$r" for-each-ref --format='%(refname:short)' refs/heads); do
      case "$in_wt" in *" $branch "*) continue ;; esac
      [ "$branch" = "$(base "$r")" ] && continue
      pr=$(pr_of "$branch"); case "$pr" in *" merged"|*" closed") ;; *) continue ;; esac
      echo "- \`$l\` branch \`$branch\`: $pr"; found=1
    done
  done
  [ "$found" = 1 ] || [ -n "$unchecked" ] || echo "- none"
  [ -z "$unchecked" ] || echo "- not checked (no gh or remote):$unchecked"
  echo "$end"
} >"$block"

tmp=$(mktemp)
awk -v b="$begin" -v e="$end" -v blk="$block" '
  $0 == b { while ((getline l < blk) > 0) print l; skip = 1; next }
  $0 == e { skip = 0; next }
  !skip' "$file" >"$tmp"
perl -pi -e 's/Last sync: \d{4}-\d{2}-\d{2}/"Last sync: " . `date +%F` =~ s{\n}{}r/e' "$tmp"
mv "$tmp" "$file"
rm -f "$block"
echo "memory-state: wrote base branches, open PRs and cleanup into memory/PROJECT_STATE.md"
